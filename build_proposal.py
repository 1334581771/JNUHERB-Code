P(
    'HerbiV 概率联合评分公式：\n\n'
    '    Chemical Score = 1 - ∏(1 - sᵢ)\n'
    '    其中 sᵢ 为第 i 个化合物对特定蛋白的 Combined Score（已归一化到 0-1）\n\n'
    '    TCM Score = 1 - ∏(1 - ChemScoreⱼ)\n'
    '    其中 ChemScoreⱼ 为该草药中第 j 个化学成分对特定蛋白的 Chemical Score\n\n'
    '    Formula Score = 1 - ∏(1 - TCMScoreₖ)\n'
    '    其中 TCMScoreₖ 为该方剂中第 k 味草药对特定蛋白的 TCM Score\n\n'
    '    Importance Score = mean(TCMScoreₖ / FormulaScore across all target proteins)\n'
    '    最终重要性评分为各靶点评分的加权平均值。'
)

